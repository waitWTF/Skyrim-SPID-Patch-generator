using System.IO;
using System.Text;

namespace WearableDistributor;

public static class MerchantStockService
{
    public const string Blacksmiths = "Blacksmiths";
    public const string GeneralGoods = "General goods";
    public const string Clothing = "Clothing traders";
    public static IReadOnlyList<string> Categories { get; } = [Blacksmiths, GeneralGoods, Clothing];
    internal const string RelativePath = "SKSE/Plugins/SkyPatcher/container/WearableDistributor/WearableDistributor_Merchandise.ini";

    internal static string? Classify(string evidence)
    {
        var text = evidence.ToLowerInvariant();
        if (text.Contains("blacksmith")) return Blacksmiths;
        if (text.Contains("clothing") || text.Contains("clothes") || text.Contains("raiment") || text.Contains("tailor")) return Clothing;
        if (text.Contains("vendoritemsmisc") || text.Contains("generalgoods") || text.Contains("general goods") || text.Contains("pawnbroker")) return GeneralGoods;
        return null;
    }

    internal static List<MerchantStockRule> Build(PluginPatchOptions config)
    {
        if (config.MerchantCategories.Count == 0) return [];
        if (config.MerchantCategories.Any(category => !Categories.Contains(category))) throw new InvalidDataException("Unknown trader category.");
        foreach (var category in config.MerchantCategories)
            if (!config.MerchantTargets.Any(target => target.Category == category))
                throw new InvalidDataException($"No confirmed merchant containers were found for {category}. Rescan or untick that trader category.");
        var rules = new List<MerchantStockRule>();
        if ((long)config.MerchantTargets.Count(target => config.MerchantCategories.Contains(target.Category)) * (config.Pieces.Count(piece => piece.Include) + (config.IncludeMerchandiseWeapons ? config.Source.Weapons.Count : 0)) > 250_000)
            throw new InvalidDataException("This merchandise selection is too large. Choose fewer parts or trader categories for this named outfit.");
        foreach (var target in config.MerchantTargets.Where(target => config.MerchantCategories.Contains(target.Category)))
        {
            foreach (var piece in config.Pieces.Where(piece => piece.Include))
                rules.Add(new(target.Plugin, target.LocalId, target.Category, piece.Plugin, piece.LocalId, "Armor"));
            if (config.IncludeMerchandiseWeapons && target.Category != Clothing)
                foreach (var weapon in config.Source.Weapons.Where(weapon => weapon.Include))
                    rules.Add(new(target.Plugin, target.LocalId, target.Category, weapon.Plugin, weapon.LocalId, "Weapon"));
        }
        // A shared container must not receive a weapon through a second category when it also serves a clothing trader.
        var clothingContainers = config.MerchantTargets.Where(target => target.Category == Clothing)
            .Select(target => Key(target.Plugin, target.LocalId)).ToHashSet(StringComparer.OrdinalIgnoreCase);
        rules.RemoveAll(rule => rule.ItemKind == "Weapon" && clothingContainers.Contains(Key(rule.ContainerPlugin, rule.ContainerId)));
        return rules.Distinct().ToList();
    }

    private static string Key(string plugin, uint id) => plugin + "|" + id.ToString("X6");
    private static string Form(string plugin, uint id)
    {
        DistributionRuleCompiler.ValidatePluginName(plugin);
        if (id == 0 || id > 0xFFFFFF) throw new InvalidDataException("Invalid merchant/item local FormID.");
        return plugin + "|" + id.ToString("X6");
    }

    internal static string Compile(PatchManifest manifest)
    {
        var rules = manifest.Entries.SelectMany(entry => entry.MerchantStock).ToList();
        var text = new StringBuilder("; Generated by Skyrim SPID Patch Generator. Requires SkyPatcher, including when NPC outfits use SPID.\n; Adds one of each selected item to merchant stock. NPC chance does not affect shop stock.\n");
        var clothing = rules.Where(rule => rule.Category == Clothing).Select(rule => Key(rule.ContainerPlugin, rule.ContainerId)).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var rule in rules)
            if (!Categories.Contains(rule.Category) || rule.ItemKind is not ("Armor" or "Weapon") || rule.ItemKind == "Weapon" && rule.Category == Clothing)
                throw new InvalidDataException("Invalid merchandise rule: clothing traders cannot receive weapons.");
        foreach (var group in rules.Where(rule => rule.ItemKind != "Weapon" || !clothing.Contains(Key(rule.ContainerPlugin, rule.ContainerId)))
                     .GroupBy(rule => Form(rule.ContainerPlugin, rule.ContainerId), StringComparer.OrdinalIgnoreCase).OrderBy(group => group.Key, StringComparer.OrdinalIgnoreCase))
        {
            var items = group.Select(rule => Form(rule.ItemPlugin, rule.ItemId)).Distinct(StringComparer.OrdinalIgnoreCase).Order(StringComparer.OrdinalIgnoreCase);
            foreach (var chunk in items.Chunk(64))
                text.Append("filterByContainers=").Append(group.Key).Append(":addOnceToContainers=").AppendJoin(',', chunk.Select(item => item + "~1")).Append('\n');
        }
        return text.ToString();
    }

    internal static string? Stage(string directory, PatchManifest manifest)
    {
        if (!manifest.Entries.Any(entry => entry.MerchantStock.Count > 0)) return null;
        var path = PatchOutputTransaction.ManagedPath(directory, RelativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, Compile(manifest), new UTF8Encoding(false));
        return path;
    }

    internal static string Describe(PatchManifestEntry entry) => entry.MerchantStock.Count == 0 ? "No trader merchandise." :
        "Merchandise: " + string.Join(", ", entry.MerchantStock.Select(rule => rule.Category).Distinct()) +
        $"\nStock containers: {entry.MerchantStock.Select(rule => Key(rule.ContainerPlugin, rule.ContainerId)).Distinct(StringComparer.OrdinalIgnoreCase).Count()}" +
        $"\nStock items: {entry.MerchantStock.Select(rule => Key(rule.ItemPlugin, rule.ItemId)).Distinct(StringComparer.OrdinalIgnoreCase).Count()}" +
        "\nRequires SkyPatcher. Clothing traders receive no weapons. NPC chance does not apply to shop stock.";

    internal static void Validate(string directory, PatchManifest manifest)
    {
        var path = PatchOutputTransaction.ManagedPath(directory, RelativePath);
        var expected = manifest.Entries.Any(entry => entry.MerchantStock.Count > 0);
        if (!expected && File.Exists(path)) throw new InvalidDataException("Unexpected merchandise rules. Restore or regenerate the complete output.");
        if (expected && (!File.Exists(path) || File.ReadAllText(path).Replace("\r\n", "\n") != Compile(manifest)))
            throw new InvalidDataException("Merchant stock rules are missing or changed. Restore a backup or regenerate the output.");
    }
}
