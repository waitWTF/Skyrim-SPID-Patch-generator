using System.Globalization;
using System.IO;
using System.Text;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Binary.Translations;
using Mutagen.Bethesda.Plugins.Records;
using Mutagen.Bethesda.Skyrim;

namespace WearableDistributor;

public sealed record PatchGenerationResult(string PluginPath, string DistributionPath, int OutfitCount, int DistributionCount, IReadOnlyList<string> Masters, string Framework);

public static class PatchGenerator
{
    public const string OutputPluginName = "WearableDistributor.esp";
    public const string OutputIniName = "WearableDistributor_DISTR.ini";

    public static PatchGenerationResult Generate(IEnumerable<PluginPatchOptions> sourceOptions, string outputDirectory, string framework)
    {
        var useSkyPatcher = framework.Equals("SkyPatcher", StringComparison.OrdinalIgnoreCase);
        var configurations = sourceOptions.ToList();
        if (configurations.Count == 0) throw new InvalidOperationException("No plugin configurations were provided.");

        var outfits = configurations
            .Select(configuration => new
            {
                Configuration = configuration,
                Pieces = configuration.Pieces.Where(piece => piece.Include).ToList(),
                Targets = configuration.Keywords.ToList(),
                Chance = ParseChance(configuration.Chance)
            })
            .Where(item => item.Pieces.Count > 0)
            .ToList();
        if (outfits.Count == 0) throw new InvalidOperationException("Include at least one outfit piece before generating the patch.");

        foreach (var item in outfits)
        {
            if (item.Targets.Count == 0) throw new InvalidOperationException($"{item.Configuration.Source.Plugin} has no NPC target. Add at least one NPC group.");
            if (useSkyPatcher && item.Chance != 100)
                throw new InvalidOperationException("SkyPatcher's NPC outfit rules do not support a per-NPC chance. Choose 100% for a full outfit assignment, or select SPID in Preferences to use the configured chance.");
        }

        Directory.CreateDirectory(outputDirectory);
        var outputPlugin = Path.Combine(outputDirectory, OutputPluginName);
        var relativeIniPath = useSkyPatcher
            ? Path.Combine("SKSE", "Plugins", "SkyPatcher", "npc", "WearableDistributor", "WearableDistributor.ini")
            : OutputIniName;
        var outputIni = Path.Combine(outputDirectory, relativeIniPath);
        var tempDirectory = Path.Combine(outputDirectory, $".WearableDistributor-{Guid.NewGuid():N}");
        Directory.CreateDirectory(tempDirectory);
        var tempPlugin = Path.Combine(tempDirectory, OutputPluginName);
        var tempIni = Path.Combine(tempDirectory, relativeIniPath);

        try
        {
            var masters = outfits.SelectMany(item => item.Pieces)
                .Select(piece => ModKey.FromFileName(piece.Plugin))
                .Where(key => !string.Equals(key.FileName, OutputPluginName, StringComparison.OrdinalIgnoreCase))
                .Distinct()
                .OrderBy(key => key.FileName.ToString(), StringComparer.OrdinalIgnoreCase)
                .ToList();

            var outputModKey = ModKey.FromFileName(OutputPluginName);
            var outputMod = new SkyrimMod(outputModKey, SkyrimRelease.SkyrimSE);
            outputMod.ModHeader.Author = "Wearable Distributor";
            outputMod.ModHeader.Description = "Generated NPC outfits. Keep enabled with WearableDistributor_DISTR.ini.";
            foreach (var master in masters)
                outputMod.ModHeader.MasterReferences.Add(new MasterReference { Master = master });

            Directory.CreateDirectory(Path.GetDirectoryName(tempIni)!);
            var lines = new List<string>
            {
                "; Generated by Wearable Distributor.",
                useSkyPatcher
                    ? "; SkyPatcher NPC patch. Chance is not supported; rules assign the default outfit to every matching NPC."
                    : "; SPID patch. Keep this file and WearableDistributor.esp installed and enabled together.",
                "; Group choices from separate categories are combined as required filters.",
                ""
            };
            var outfitIndex = 0;
            var distributionCount = 0;
            foreach (var item in outfits)
            {
                outfitIndex++;
                var pluginLabel = Path.GetFileNameWithoutExtension(item.Configuration.Source.Plugin);
                var editorId = $"WD_{outfitIndex:D4}_{SanitizeEditorId(pluginLabel)}";
                var outfit = outputMod.Outfits.AddNew(editorId) ?? throw new InvalidOperationException("Mutagen could not allocate an outfit record.");
                var outfitItems = outfit.Items ?? throw new InvalidOperationException("Mutagen did not initialize the outfit item list.");
                foreach (var piece in item.Pieces)
                {
                    var sourceKey = new FormKey(ModKey.FromFileName(piece.Plugin), piece.LocalId);
                    outfitItems.Add(new FormLink<IOutfitTargetGetter>(sourceKey));
                }

                lines.Add($"; {item.Configuration.Source.Plugin} — {item.Pieces.Count} piece(s)");
                var keywordGroups = item.Targets.Where(target => target.TargetKind.Equals("Keyword", StringComparison.OrdinalIgnoreCase))
                    .GroupBy(target => target.Category, StringComparer.OrdinalIgnoreCase).ToList();
                var formGroups = item.Targets.Where(target => !target.TargetKind.Equals("Keyword", StringComparison.OrdinalIgnoreCase))
                    .GroupBy(target => target.Category, StringComparer.OrdinalIgnoreCase).ToList();
                var keywordCombos = ExpandGroups(keywordGroups.Select(group => group.Select(target => target.EditorId).Distinct(StringComparer.OrdinalIgnoreCase).ToList()).ToList());
                var formCombos = ExpandGroups(formGroups.Select(group => group.Select(target => FormatFormId(target.LocalId, target.Plugin)).Distinct(StringComparer.OrdinalIgnoreCase).ToList()).ToList());
                var skyPatcherTargetCombos = ExpandGroups(item.Targets
                    .GroupBy(target => target.Category, StringComparer.OrdinalIgnoreCase)
                    .Select(group => group.DistinctBy(target => target.FormId, StringComparer.OrdinalIgnoreCase).ToList()).ToList());
                var outfitId = FormatFormId(outfit.FormKey.ID, OutputPluginName);
                var trait = item.Configuration.Gender switch { "Female" => "F", "Male" => "M", _ => "NONE" };

                if (useSkyPatcher)
                {
                    foreach (var targetCombo in skyPatcherTargetCombos)
                    {
                        var rule = new List<string>();
                        AddSkyPatcherFilter(rule, "filterByKeywords", targetCombo, "Keyword");
                        AddSkyPatcherFilter(rule, "filterByFactions", targetCombo, "Faction");
                        AddSkyPatcherFilter(rule, "filterByClass", targetCombo, "Class");
                        AddSkyPatcherFilter(rule, "filterByRaces", targetCombo, "Race");
                        if (item.Configuration.Gender != "Any") rule.Add($"filterByGender={item.Configuration.Gender.ToLowerInvariant()}");
                        rule.Add($"outfitDefault={outfitId}");
                        lines.Add(string.Join(':', rule));
                        distributionCount++;
                    }
                }
                else
                {
                    foreach (var keywordCombo in keywordCombos)
                    foreach (var formCombo in formCombos)
                    {
                        var stringFilter = keywordCombo.Count > 0 ? string.Join('+', keywordCombo) : "NONE";
                        var formFilter = formCombo.Count > 0 ? string.Join('+', formCombo) : "NONE";
                        lines.Add($"Outfit = {outfitId}|{stringFilter}|{formFilter}|NONE|{trait}|NONE|{item.Chance.ToString(CultureInfo.InvariantCulture)}");
                        distributionCount++;
                    }
                }
                lines.Add("");
            }

            outputMod.BeginWrite.ToPath(tempPlugin).WithNoLoadOrder().Write();
            File.WriteAllText(tempIni, string.Join(Environment.NewLine, lines), new UTF8Encoding(false));
            ValidateGeneratedPlugin(tempPlugin, outfitIndex, masters);
            ValidateGeneratedIni(tempIni, distributionCount, useSkyPatcher);

            File.Copy(tempPlugin, outputPlugin, true);
            Directory.CreateDirectory(Path.GetDirectoryName(outputIni)!);
            File.Copy(tempIni, outputIni, true);
            return new PatchGenerationResult(outputPlugin, outputIni, outfitIndex, distributionCount, masters.Select(key => key.FileName.ToString()).ToList(), useSkyPatcher ? "SkyPatcher" : "SPID");
        }
        finally
        {
            try { Directory.Delete(tempDirectory, true); } catch { }
        }
    }

    private static int ParseChance(string raw)
    {
        var normalized = raw.Trim().TrimEnd('%');
        if (!int.TryParse(normalized, NumberStyles.None, CultureInfo.InvariantCulture, out var chance) || chance is < 1 or > 100)
            throw new InvalidOperationException($"Distribution chance must be a whole number from 1 to 100. Received: '{raw}'.");
        return chance;
    }

    private static string FormatFormId(uint localId, string plugin) => $"0x{localId:X6}~{plugin}";

    private static void AddSkyPatcherFilter(List<string> rule, string filterName, IEnumerable<KeywordChoice> targets, string targetKind)
    {
        var values = targets.Where(target => target.TargetKind.Equals(targetKind, StringComparison.OrdinalIgnoreCase))
            .Select(target => FormatFormId(target.LocalId, target.Plugin)).ToList();
        if (values.Count > 0) rule.Add($"{filterName}={string.Join(',', values)}");
    }

    private static string SanitizeEditorId(string source)
    {
        var safe = new string(source.Select(character => char.IsAsciiLetterOrDigit(character) || character == '_' ? character : '_').ToArray());
        return string.IsNullOrWhiteSpace(safe) ? "Outfit" : safe.Length > 48 ? safe[..48] : safe;
    }

    private static List<List<T>> ExpandGroups<T>(IReadOnlyList<List<T>> groups)
    {
        var combinations = new List<List<T>> { new() };
        foreach (var group in groups)
        {
            var next = new List<List<T>>();
            foreach (var combination in combinations)
                foreach (var value in group)
                    next.Add([.. combination, value]);
            combinations = next;
        }
        return combinations;
    }

    private static void ValidateGeneratedPlugin(string path, int expectedOutfits, IReadOnlyCollection<ModKey> expectedMasters)
    {
        using var readBack = SkyrimMod.CreateFromBinaryOverlay(new Noggog.FilePath(path), SkyrimRelease.SkyrimSE);
        if (readBack.Outfits.Count != expectedOutfits)
            throw new InvalidDataException($"Generated plugin validation failed: expected {expectedOutfits} outfit records, found {readBack.Outfits.Count}.");
        var missingMasters = expectedMasters.Where(master => !readBack.ModHeader.MasterReferences.Any(reference => reference.Master == master)).ToList();
        if (missingMasters.Count > 0)
            throw new InvalidDataException($"Generated plugin is missing master references: {string.Join(", ", missingMasters.Select(master => master.FileName))}.");
    }

    private static void ValidateGeneratedIni(string path, int expectedDistributions, bool skyPatcher)
    {
        var actual = File.ReadLines(path).Count(line => skyPatcher
            ? line.Contains("outfitDefault=", StringComparison.Ordinal)
            : line.StartsWith("Outfit = ", StringComparison.Ordinal));
        if (actual != expectedDistributions || actual == 0)
            throw new InvalidDataException($"Generated SPID INI validation failed: expected {expectedDistributions} outfit distribution rows, found {actual}.");
    }
}
